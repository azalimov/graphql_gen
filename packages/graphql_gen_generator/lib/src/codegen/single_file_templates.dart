import 'package:path/path.dart' as p;

import '../config.dart';
import '../naming.dart';
import '../schema/schema.dart';
import 'type_mapper.dart';

/// Renders the one-per-schema files: enums, converters, operation names,
/// argument builders and the barrel.
class SingleFileTemplates {
  SingleFileTemplates(this.config, this.schema, this.types);

  final GraphQLGenConfig config;
  final GqlSchema schema;
  final TypeMapper types;

  String get _schemaFileName => p.basename(config.schema.file);

  String enumFile(GqlEnumType type) =>
      'enum ${type.name} {\n  ${type.values.join(',\n  ')},\n}\n';

  /// Converters that keep enum values as Dart enums in `toJson`, so
  /// `GraphQLArgumentBuilder` writes them unquoted.
  String enumConverters() {
    final b = StringBuffer()
      ..writeln("import '${config.modelsImport}';")
      ..writeln()
      ..writeln(
        '/// Utility functions for converting Dart enums to '
        'GraphQL-compatible formats.',
      )
      ..writeln('///')
      ..writeln(
        '/// GraphQL expects enum values to be sent without the enum '
        'type name,',
      )
      ..writeln(
        "/// so we need to convert Dart's `EnumName.VALUE` to just "
        '`VALUE`.',
      )
      ..writeln()
      ..writeln('// Required enum converters (for non-nullable fields)')
      ..writeln()
      ..writeln('// Nullable enum converters (for nullable fields)')
      ..writeln();
    for (final name in schema.enums.keys) {
      b
        ..writeln('/// Specific converter for $name (required)')
        ..writeln('Object ${lowerFirst(name)}ToJson($name value) => value;')
        ..writeln()
        ..writeln('/// Specific converter for $name (nullable)')
        ..writeln('Object? nullable${name}ToJson($name? value) => value;')
        ..writeln();
    }
    return b.toString();
  }

  /// Constant names of every root field of [root].
  String? operations(GqlObjectType? root, GeneratedFile file, String label) {
    if (root == null || root.fields.isEmpty) return null;
    final names = root.fields.map((f) => f.name).toSet().toList()..sort();
    final b = StringBuffer()
      ..writeln('/// GraphQL $label Operations')
      ..writeln('/// Auto-generated from $_schemaFileName')
      ..writeln('class ${config.className(file)} {');
    for (final name in names) {
      b.writeln("  static const String ${safeFieldName(name)} = '$name';");
    }
    b.writeln('}');
    return b.toString();
  }

  /// Typed `GraphQLArgumentBuilder` factories for root fields with
  /// arguments.
  String? arguments(GqlObjectType? root, GeneratedFile file, String label) {
    final fields = [
      for (final field in root?.fields ?? <GqlField>[])
        if (field.arguments.isNotEmpty) field,
    ]..sort((a, b) => a.name.compareTo(b.name));
    if (fields.isEmpty) return null;

    final b = StringBuffer()
      ..writeln('// ignore_for_file: dangling_library_doc_comments')
      ..writeln('/// GraphQL $label Arguments')
      ..writeln('/// Auto-generated from $_schemaFileName')
      ..writeln("import '${config.runtimeImport}';")
      ..writeln("import '${config.modelsImport}';")
      ..writeln()
      ..writeln('class ${config.className(file)} {');

    for (final field in fields) {
      b
        ..writeln('  /// ${field.name}')
        ..writeln(
          '  static GraphQLArgumentBuilder ${safeFieldName(field.name)}({',
        );
      for (final arg in field.arguments) {
        final required = arg.type.isNonNull && !arg.hasDefault;
        final base = types.base(arg.type);
        final type = required ? 'required $base' : '$base?';
        b.writeln('    $type ${safeFieldName(arg.name)},');
      }
      b
        ..writeln('  }) {')
        ..writeln('    return GraphQLArgumentBuilder()');
      for (final (index, arg) in field.arguments.indexed) {
        final last = index == field.arguments.length - 1;
        b.writeln(
          "        .withArgument('${arg.name}', "
          '${_argumentValue(arg)})${last ? ';' : ''}',
        );
      }
      b
        ..writeln('  }')
        ..writeln();
    }
    b.writeln('}');
    return b.toString();
  }

  String _argumentValue(GqlField arg) {
    final name = safeFieldName(arg.name);
    final nullable = !(arg.type.isNonNull && !arg.hasDefault);
    final q = nullable ? '?' : '';
    final ref = arg.type;
    if (!types.isInput(ref.baseName)) return name;
    if (ref is NamedRef) return '$name$q.toJson()';
    if (ref is ListRef && ref.ofType is NamedRef) {
      final element = ref.ofType.isNonNull ? 'e.toJson()' : 'e?.toJson()';
      return '$name$q.map((e) => $element).toList()';
    }
    return name;
  }

  String barrel(Iterable<String> exports) {
    final sorted = exports.toList()..sort();
    final b = StringBuffer()
      ..writeln('// GENERATED by graphql_gen. Do not edit by hand.')
      ..writeln();
    for (final path in sorted) {
      b.writeln("export '$path';");
    }
    return b.toString();
  }
}
